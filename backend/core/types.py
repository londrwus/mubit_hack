class ArmSummary(BaseModel):
    """Headline numbers for one arm (race_finished event, GET /api/races/{id})."""

    arm: ArmKind
    best_score: float | None = None
    best_experiment_id: str | None = None
    experiments_finished: int = 0
    experiments_failed: int = 0
    gpu_cost_usd: float = 0.0
    llm_cost_usd: float = 0.0
    gpu_idle_pct: float = 0.0              # idle time / paid time * 100
    time_to_target_s: float | None = None  # None = target never reached
    cost_to_target_usd: float | None = None
    llm_calls: int = 0
    llm_invalid_calls: int = 0
    llm_p50_latency_ms: float | None = None

    @computed_field  # type: ignore[prop-decorator]
    @property
    def total_cost_usd(self) -> float:
        return self.gpu_cost_usd + self.llm_cost_usd

