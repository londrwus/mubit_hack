"""Shared types: the contract every module codes against.

Conventions (see backend/core/README.md):
- IDs are strings (uuid4 hex), generated by whoever creates the row.
- Timestamps are float Unix epoch seconds (``time.time()``); ``MetricPoint.t`` is
  seconds since the run started.
- Money is USD floats.
"""

from __future__ import annotations

import json
import time
import uuid
from enum import StrEnum
from typing import Any, TypeAlias

from pydantic import BaseModel, ConfigDict, Field, computed_field, field_validator, model_validator


def new_id() -> str:
    """A fresh string ID (uuid4 hex). Use for every row/entity ID."""
    return uuid.uuid4().hex


def now() -> float:
    """Current Unix epoch seconds."""
    return time.time()


# --------------------------------------------------------------------------- enums


class ArmKind(StrEnum):
    opus = "opus"      # Arm A: every step on claude-opus-5-5 through Mubit
    mubit = "mubit"    # Arm B: same calls, served by Mubit adapters once routed
    opus_bm = "opus_bm"  # D36: "Busy Machines with Opus": Opus on every step + the BM engine features
    optuna = "optuna"  # Arm C: no-LLM baseline (Optuna / random search)
    mock = "mock"      # dev only: deterministic fake LLM, never in a benchmark
    # Ablation only (never a benchmark / headline arm): the same researcher with a smaller,
    # faster model (claude-haiku-5-5 through Mubit, record off). A smaller faster model in the
    # same loop, NOT a Mubit adapter. Tests the planner-speed mechanism (R43 projection).
    fast = "fast"


class StepType(StrEnum):
    propose_experiments = "propose_experiments"
    diagnose_run = "diagnose_run"
    judge_improvement = "judge_improvement"
    early_stop = "early_stop"  # D34: continue/stop a running experiment at fixed checkpoints


class ExperimentStatus(StrEnum):
    pending = "pending"      # proposed, not launched yet
    running = "running"
    succeeded = "succeeded"  # finished and produced a score
    failed = "failed"        # crashed / NaN / OOM / invalid config (see RunResult.error)
    timed_out = "timed_out"  # exceeded budget_s + runner grace
    cancelled = "cancelled"


class SlotState(StrEnum):
    busy = "busy"
    idle = "idle"


class Direction(StrEnum):
    min = "min"
    max = "max"


# --------------------------------------------------------------------------- compute

ExperimentConfig: TypeAlias = dict[str, Any]
"""A concrete config: {param_name: value}, keys from the target's config_space."""


class Slot(BaseModel):
    """One unit of concurrency a runner offers (a GPU, or a CPU container)."""

    slot_id: str            # stable within a runner, e.g. "modal-L4-0", "local-cpu-3"
    index: int              # 0..N-1
    hardware: str           # "L4" | "CPU" | "T4" | ... (never "H100" without a reason)
    runner: str             # Runner.name


class RunHandle(BaseModel):
    """Returned by Runner.launch; passed back to wait()/cancel()."""

    run_id: str = Field(default_factory=new_id)  # runner-local ID; also MetricPoint.experiment_id
    runner: str
    target: str
    config: ExperimentConfig
    seed: int
    budget_s: int
    hardware: str
    run_ref: str | None = None   # Modal call ID (FunctionCall.object_id) or local PID
    started_at: float = Field(default_factory=now)


class MetricPoint(BaseModel):
    """One streamed metric value (``metrics`` table row)."""

    experiment_id: str  # runner fills handle.run_id; the scheduler maps it to the experiment
    step: int
    t: float            # seconds since the run started
    name: str
    value: float


class RunResult(BaseModel):
    """Final outcome of one run. Runners return this from wait(); they never raise for
    training failures (those become status=failed + error)."""

    score: float | None                     # target's held-out metric; None unless succeeded
    status: ExperimentStatus
    metrics: dict[str, float] = Field(default_factory=dict)  # summary (final train loss, steps, ...)
    logs_tail: list[str] = Field(default_factory=list)       # last <=50 log lines (for diagnose_run)
    is_trap: bool = False                    # ground truth: config enabled the contamination trap
    run_ref: str | None = None
    started_at: float
    ended_at: float
    hardware: str
    error: str | None = None

    @computed_field  # type: ignore[prop-decorator]
    @property
    def duration_s(self) -> float:
        return max(0.0, self.ended_at - self.started_at)


