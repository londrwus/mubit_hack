    session_id: str                      # "race-{id}/{arm}/seed-{n}" (metadata.user_id)
    step_type: StepType
    mubit_request_id: str | None = None  # response header x-middleware-request-id
    model: str                           # provider model ID as sent, e.g. "claude-opus-5-5"
    latency_ms: float = 0.0
    input_tokens: int = 0
    cache_creation_tokens: int = 0
    cache_read_tokens: int = 0
    output_tokens: int = 0
    cost_usd: float = 0.0
    valid: bool = False                  # reply parsed and validated against the step schema
    is_retry: bool = False
    is_fallback: bool = False
    is_replay: bool = False              # served from record/replay cache (dev only)
    recorded: bool = False               # False => sent with "x-middleware-record: off"
    stop_reason: str | None = None
    error: str | None = None             # transport/validation error text, if any
    experiment_ids: list[str] = Field(default_factory=list)  # experiments this call produced/judged
    created_at: float = Field(default_factory=now)
    mubit_project: str | None = None     # D38: Mubit project ("A" / "B") whose key sent it; None = mock/replay
