class LLMCallRecord(BaseModel):
    """One HTTP request to the Mubit gateway (``llm_calls`` table row).
    A retry or a fallback is a separate record with is_retry / is_fallback set."""

    id: str = Field(default_factory=new_id)
    arm_id: str | None = None            # filled by the caller that owns the arm row
